#!/usr/bin/env python3
"""Regenerate the checked-in presentation SPIR-V header from its GLSL sources."""
import argparse
from pathlib import Path
import struct
import subprocess

ap = argparse.ArgumentParser(description=__doc__)
ap.add_argument('--glslang', default='glslangValidator')
ap.add_argument('--spirv-val', default='spirv-val')
args = ap.parse_args()
root = Path(__file__).resolve().parents[1]
work = root / 'build/present-shaders'; work.mkdir(parents=True, exist_ok=True)
text = '// Generated by scripts/build_present_shaders.py. Do not hand-edit.\n#pragma once\n#include <stdint.h>\n'
for stage in ('vert', 'frag'):
    output = work / (stage + '.spv')
    subprocess.run([args.glslang, '-V', str(root / f'dm/gfx/nvn/shaders/tri.{stage}'), '-o', str(output)], check=True)
    subprocess.run([args.spirv_val, '--target-env', 'vulkan1.0', str(output)], check=True)
    words = struct.unpack('<' + 'I' * (output.stat().st_size // 4), output.read_bytes())
    text += f'static const uint32_t sh_tri_{stage}_len = {len(words)};\nstatic const uint32_t sh_tri_{stage}[] = {{\n'
    text += ',\n'.join(','.join(f'0x{w:08x}' for w in words[i:i+8]) for i in range(0,len(words),8)) + '\n};\n'
(root / 'dm/gfx/nvn/nvn_sh_tri.h').write_bytes(text.replace('\n', '\r\n').encode())
